import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";
import ts from "typescript";

const root = new URL("../", import.meta.url);
const vendor = new URL("google-apps-script/vendor/noble-hashes-2.4.0/", root);
const provenanceUrl = new URL("PROVENANCE.json", vendor);
const provenance = JSON.parse(readFileSync(provenanceUrl, "utf8"));
const check = process.argv.includes("--check"), updateHash = process.argv.includes("--update-hash");
assert.ok(!(check && updateHash), "Choose either --check or --update-hash.");
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");

for (const [path, expected] of Object.entries(provenance.upstreamFilesSha256)) {
  assert.equal(sha256(readFileSync(new URL(path, vendor))), expected, `Vendored upstream source changed: ${path}`);
}
for (const name of ["typescript", "rolldown"]) {
  const installed = JSON.parse(readFileSync(new URL(`node_modules/${name}/package.json`, root), "utf8"));
  assert.equal(installed.version, provenance.build[name], `Use the locked ${name} version to reproduce this bundle.`);
}

const upstreamRoot = fileURLToPath(new URL("upstream/", vendor));
const inputAdapter = "export function kdfInputToBytes(data, errorTitle = '') {\n    if (typeof data === 'string')\n        return utf8ToBytes(data);\n    return abytes(data, undefined, errorTitle);\n}";
const replacement = "// Apps Script adapter: only bytes are accepted; no TextEncoder is required.\nexport function kdfInputToBytes(data, errorTitle = '') {\n    return abytes(data, undefined, errorTitle);\n}";
const build = await rolldown({
  input: fileURLToPath(new URL("entry.mjs", vendor)),
  platform: "neutral",
  treeshake: true,
  plugins: [{
    name: "apps-script-byte-input-and-class-fields",
    transform(code, id) {
      if (!id.startsWith(upstreamRoot)) return null;
      if (id.endsWith("/utils.js")) {
        assert.equal(code.split(inputAdapter).length, 2, "Upstream byte-input adapter must match exactly once.");
        assert.equal(code.split("Object.hasOwn(value, '__proto__')").length, 2, "Upstream Object.hasOwn call must match exactly once.");
        code = code.replace(inputAdapter, replacement)
          .replace("Object.hasOwn(value, '__proto__')", "Object.prototype.hasOwnProperty.call(value, '__proto__')");
      }
      // Lower unsupported class fields without adding another runtime library.
      return ts.transpileModule(code, { fileName: id, compilerOptions: {
        allowJs: true, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020, useDefineForClassFields: true,
      } }).outputText;
    },
  }],
});
let code;
try {
  const license = readFileSync(new URL("LICENSE", vendor), "utf8");
  const { output } = await build.generate({
    format: "iife", name: "NODE_PASSWORD_KDF", minify: false,
    banner: `/* @noble/hashes ${provenance.version}; generated by scripts/generate-password-kdf.mjs\n${license}\n*/`,
  });
  assert.equal(output.length, 1, "The Apps Script KDF must be one self-contained file.");
  code = output[0].code.split("\n").filter(line => !line.startsWith("//#region") && !line.startsWith("//#endregion")).join("\n");
} finally {
  await build.close();
}

// These are runtime dependencies, not comment/string matches. Fail generation
// rather than shipping a bundle Apps Script cannot parse or execute.
const syntax = ts.createSourceFile("password-kdf.gs", code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const forbidden = new Set(["TextEncoder", "TextDecoder", "crypto", "SubtleCrypto", "Buffer", "process", "require", "setTimeout", "setInterval", "fetch", "window", "navigator"]);
function inspect(node) {
  assert.ok(!ts.isImportDeclaration(node) && !ts.isExportDeclaration(node), "Apps Script cannot load ES modules.");
  assert.ok(!ts.isPropertyDeclaration(node), "Apps Script cannot parse class fields.");
  const ownProcessMethod = ts.isIdentifier(node) && node.text === "process" && (
    ts.isPropertyAccessExpression(node.parent) && node.parent.name === node && node.parent.expression.kind === ts.SyntaxKind.ThisKeyword
    || ts.isMethodDeclaration(node.parent) && node.parent.name === node
  );
  assert.ok(!ts.isIdentifier(node) || !forbidden.has(node.text) || ownProcessMethod, `Unavailable Apps Script API: ${node.text}`);
  ts.forEachChild(node, inspect);
}
inspect(syntax);

const hash = sha256(code);
if (!updateHash) assert.equal(hash, provenance.bundleSha256, "Bundle hash changed. Review the diff, then explicitly use --update-hash.");
const bundleUrl = new URL(provenance.bundleFile, vendor);
const start = "/* BEGIN GENERATED PASSWORD KDF */", end = "/* END GENERATED PASSWORD KDF */";
const generated = `${start}\n${code.trimEnd()}\n${end}`;
const backendUrl = new URL("google-apps-script/Code.gs", root);
const previous = readFileSync(backendUrl, "utf8"), from = previous.indexOf(start), to = previous.indexOf(end);
assert.ok((from < 0) === (to < 0) && (from < 0 || from < to), "Generated KDF markers are inconsistent.");
assert.ok(previous.indexOf(start, from + 1) < 0 && previous.indexOf(end, to + 1) < 0, "Generated KDF markers must be unique.");
const next = from < 0 ? `${previous.trimEnd()}\n\n${generated}\n` : `${previous.slice(0, from)}${generated}${previous.slice(to + end.length)}`;
if (check) {
  assert.equal(readFileSync(bundleUrl, "utf8"), code, "Regenerate the committed KDF bundle.");
  assert.equal(previous, next, "Regenerate the inline Apps Script KDF.");
} else {
  if (updateHash) { provenance.bundleSha256 = hash; writeFileSync(provenanceUrl, JSON.stringify(provenance, null, 2) + "\n"); }
  writeFileSync(bundleUrl, code);
  writeFileSync(backendUrl, next);
}
